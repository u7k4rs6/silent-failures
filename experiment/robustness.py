"""Robustness checks -> data/derived/robustness.md (no API calls).
1. Failed generations re-run with a 16k token limit and judged by GLM 5.2: what the failed answers actually contain.
2. Second judges on brand bias + sycophancy: agreement with GLM 5.2, bounds, DarkBench replay, artifact probe.
"""
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).parent))
from score import ROOT, read, gen_state, judge_state, extract_json  # noqa: E402

items = pd.read_csv(ROOT / "data/derived/items.csv")
fb = pd.read_csv(ROOT / "data/derived/flip_bounds.csv")
L = ["# Robustness checks", "", "Generated by experiment/robustness.py. TODO in report: say Qwen is *tied* for least brand-biased under DarkBench rules (6 vs DeepSeek's 7 of 110).", ""]
block = lambda title, df: L.extend([f"## {title}", "", "```", df.to_string(), "```", ""])

# 1. re-run of failed generations
rr = {(r["model"], r["item_id"]): r for r in read("rerun_16k")}
rj = {(r["target_model"], r["item_id"]): r for r in read("judge_rerun16k")}
rows = []
for (m, i), g in rr.items():
    js, lab = judge_state(rj[(m, i)], g["category"]) if (m, i) in rj else (None, None)
    rows.append({"model": m, "item_id": i, "rerun_gen": gen_state(g), "rerun_judge": js, "rerun_label": lab})
if rows:
    rdf = pd.DataFrame(rows)
    est = items.merge(rdf, on=["model", "item_id"], how="left")
    rec = (est.rerun_gen == "ok") & (est.rerun_judge == "ok")
    est["est"] = est.label.where(est.state == "ok")
    est.loc[(est.state != "ok") & rec, "est"] = est.rerun_label
    failed = est[est.state != "ok"]
    block("Re-run of failed generations (16k tokens): outcome by model", pd.crosstab(rdf.model, rdf.rerun_gen))
    block("Recovered failed answers: count and share showing the pattern", failed[failed.est.notna()].groupby(["model", "category"]).est.agg(["count", "mean"]).round(3))
    est_rows = []
    for scope in ["overall", "brand-bias", "sycophancy"]:
        d = est if scope == "overall" else est[est.category == scope]
        g = d.groupby("model")
        t = pd.DataFrame({"failed": g.state.apply(lambda s: (s != "ok").sum()),
                          "recovered": g.apply(lambda x: ((x.state != "ok") & x.est.notna()).sum()),
                          "estimate": g.est.mean()})
        t = t.join(fb[fb.scope == scope].set_index("model")[["darkbench", "lower", "upper"]])
        block(f"Estimate with recovered answers vs DarkBench replay and bounds: {scope}", t.round(3))
        est_rows.append(t.estimate.rename_axis("model").reset_index().assign(scope=scope))
    pd.concat(est_rows).to_csv(ROOT / "data/derived/rerun_estimate.csv", index=False)

# 2. second judges
for tag, name in [("_qwen397", "qwen3.5-397b"), ("_gemma26", "gemma-4-26b-a4b-it")]:
    jr = read("judge" + tag)
    if not jr:
        continue
    rows = []
    for r in jr:
        js, lab = judge_state(r, r["category"])
        inv = int((extract_json(r["response"]["output_text"]) or {}).get("invalid") in (1, True)) if js == "ok" else None
        rows.append({"model": r["target_model"], "item_id": r["item_id"], "j2_state": js, "j2_label": lab,
                     "j2_db": None if js != "ok" else (0 if inv else lab)})
    d = items.merge(pd.DataFrame(rows), on=["model", "item_id"])
    both = d[(d.state == "ok") & (d.j2_state == "ok")]
    po = (both.label == both.j2_label).mean()
    p1, p2 = both.label.mean(), both.j2_label.mean()
    pe = p1 * p2 + (1 - p1) * (1 - p2)
    out = []
    for (c, m), g in d.groupby(["category", "model"]):
        v = g[(g.state == "ok") & (g.j2_state == "ok")]
        k, n = int((v.j2_label == 1).sum()), len(g)
        out.append({"category": c, "model": m, "n": n, "fail": n - len(v), "darkbench_rules": g.j2_db.dropna().mean(),
                    "lower": k / n, "upper": (k + n - len(v)) / n})
    pr = [judge_state(r, r["category"]) for r in read("probe" + tag)]
    L += [f"## Second judge {name}", "",
          f"- Agreement with GLM 5.2 on {len(both)} valid answers: {po:.3f} (Cohen's kappa {(po - pe) / (1 - pe):.3f}); judge failures: {int((d.j2_state != 'ok').sum())}",
          f"- Artifact probe: {sum(1 for s, l in pr if l == 0)} of {len(pr)} scored absent, {sum(1 for s, l in pr if l == 1)} present, {sum(1 for s, l in pr if s != 'ok')} unparsed", ""]
    block(f"Bounds and DarkBench replay under {name}", pd.DataFrame(out).set_index(["category", "model"]).round(3))

(ROOT / "data/derived/robustness.md").write_text("\n".join(L) + "\n")
print("\n".join(L[:60]))
